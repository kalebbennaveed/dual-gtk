from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=root/'dual_gtk_drs_racing'
# Compile the existing expression graph to straight-line numerical code. This
# preserves the exact plant/controller equations and makes 1000-rollout checks practical.
import sys
sys.path.insert(0,str(root))
from dual_gtk_drs_racing.model import GRAPH,OUTPUTS
lines=['"""Straight-line compilation of model.GRAPH for sampled rollouts.','Generated by tools/generate_fast_model.py; regression-tested against the plant.','No fast-math transformations or alternative dynamics are used.','"""','import math','import numpy as np','from numba import njit','from .expressions import lookup','','@njit(cache=True, inline="always")','def step_and_tire(state, mu, speed, offset, offset_rate, k, ds):']
inputs=[f'state[{i}]' for i in range(7)]+['mu','speed','offset','offset_rate']
for i,(op,a,b,c) in enumerate(GRAPH):
    op,a,b=int(op),int(a),int(b)
    expression={0:lambda:repr(float(c)),1:lambda:inputs[a],2:lambda:f'v{a}+v{b}',3:lambda:f'v{a}*v{b}',4:lambda:f'1./v{a}',5:lambda:f'math.sin(v{a})',6:lambda:f'math.cos(v{a})',7:lambda:f'math.atan(v{a})',8:lambda:f'max(v{a},{c!r})',9:lambda:f'min(v{a},{c!r})',10:lambda:f'lookup(v{a},k,ds)'}[op]()
    lines.append(f'    v{i} = {expression}')
lines.append('    return '+', '.join('v'+str(i) for i in list(OUTPUTS[:7])+list(OUTPUTS[24:26])))
(p/'fast_model.py').write_text('\n'.join(lines)+'\n')
